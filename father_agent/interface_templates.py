def sparkline(values: list[float], width: int = 600, height: int = 120) -> str:
    """An inline SVG polyline of ``values`` (empty with fewer than two points)."""
    if len(values) < 2:
        return ""
    low, high = min(values), max(values)
    span = (high - low) or 1.0
    step = width / (len(values) - 1)
    points = " ".join(f"{i * step:.1f},{height - 6 - (v - low) / span * (height - 12):.1f}"
                      for i, v in enumerate(values))
    return (f'<svg class="spark" viewBox="0 0 {width} {height}" preserveAspectRatio="none" '
            f'role="img" aria-label="{html.escape(VALUE_LABEL)} over time">'
            f'<polyline points="{points}"/></svg>')


