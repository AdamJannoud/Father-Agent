class Subscribers:
    """Chat ids that receive alerts, kept in ``<data_dir>/subscribers.json``."""

    def __init__(self, data_dir: Path, fixed: str = "") -> None:
        """Load saved chats; ``fixed`` (TELEGRAM_CHAT_ID) always receives alerts."""
        self.path = data_dir / "subscribers.json"
        self.fixed = {int(fixed)} if fixed.lstrip("-").isdigit() else set()
        self.chats: set[int] = set()
        try:
            self.chats = {int(c) for c in json.loads(self.path.read_text(encoding="utf-8"))}
        except FileNotFoundError:
            pass
        except (OSError, ValueError, TypeError) as exc:
            logger.warning("ignoring unreadable %s: %s", self.path, exc)

    def all(self) -> set[int]:
        """Every chat to alert."""
        return self.chats | self.fixed

    def add(self, chat_id: int) -> None:
        """Subscribe a chat and save the list."""
        self.chats.add(chat_id)
        self._save()

    def remove(self, chat_id: int) -> None:
        """Unsubscribe a chat and save the list."""
        self.chats.discard(chat_id)
        self._save()

    def _save(self) -> None:
        """Write the list; a failure is logged, never raised into a handler."""
        try:
            self.path.parent.mkdir(parents=True, exist_ok=True)
            self.path.write_text(json.dumps(sorted(self.chats)), encoding="utf-8")
        except OSError as exc:
            logger.warning("could not save subscribers: %s", exc)


class AccessMiddleware(BaseMiddleware):
    """Drops messages from users outside ALLOWED_USER_IDS (when it is set)."""

    def __init__(self, allowed: set[int]) -> None:
        """Remember the allowed user ids; an empty set allows everyone."""
        self.allowed = allowed

    async def __call__(self, handler: Callable[[TelegramObject, dict[str, Any]], Awaitable[Any]],
                       event: TelegramObject, data: dict[str, Any]) -> Any:
        """Pass the update on only when its sender is allowed."""
        user = data.get("event_from_user")
        if self.allowed and (user is None or user.id not in self.allowed):
            logger.warning("ignored a message from user %s", getattr(user, "id", "?"))
            return None
        return await handler(event, data)


def format_reading(record: dict[str, Any] | None) -> str:
    """One line describing a reading, for /status and alerts."""
    if not record:
        return "No readings yet."
    return f"{VALUE_LABEL}: {float(record['value']):,.4f} (read {record.get('timestamp', '?')})"


def format_alert(record: dict[str, Any], before: dict[str, Any] | None) -> str:
    """The message sent when the agent stores a new reading."""
    if before is None:
        return f"Watching started. {format_reading(record)}"
    return (f"Changed: {float(before['value']):,.4f} → {float(record['value']):,.4f} "
            f"{VALUE_LABEL}")


def build_dispatcher(agent: Any, subscribers: Subscribers, allowed: set[int]) -> Dispatcher:
    """Register the command handlers and the access middleware on a fresh dispatcher."""
    router = Router(name="${slug}")
    router.message.middleware(AccessMiddleware(allowed))

    @router.message(CommandStart())
    async def start(message: Message) -> None:
        """Subscribe the chat and say what the bot does."""
        subscribers.add(message.chat.id)
        await message.answer("Subscribed. I will message you when ${value_label} changes. "
                             "/status for the latest reading, /stop to unsubscribe.")

    @router.message(Command("status"))
    async def status(message: Message) -> None:
        """Reply with the latest stored reading."""
        try:
            last = agent.store.last()
        except StoreError as exc:
            logger.error("history unavailable: %s", exc)
            last = None
        await message.answer(f"{format_reading(last)}\\nChecking every "
                             f"{agent.settings.interval_seconds}s; "
                             f"{len(subscribers.all())} chat(s) subscribed.")

    @router.message(Command("check"))
    async def check(message: Message) -> None:
        """Run one agent cycle now and report the result."""
        record = await agent.run_once()
        await message.answer(format_reading(record) if record else
                             "No change since the last reading (or the source is down).")

    @router.message(Command("stop"))
    async def stop(message: Message) -> None:
        """Unsubscribe the chat."""
        subscribers.remove(message.chat.id)
        await message.answer("Unsubscribed. /start to subscribe again.")

    dispatcher = Dispatcher()
    dispatcher.include_router(router)
    return dispatcher


async def watch(bot: Bot, agent: Any, subscribers: Subscribers) -> None:
    """Run the agent on its schedule and alert every subscriber on a change."""
    while True:
        try:
            before = agent.store.last()
        except StoreError:
            before = None
        record = await agent.run_once()
        if record is not None:
            for chat_id in subscribers.all():
                try:
                    await bot.send_message(chat_id, format_alert(record, before))
                except TelegramAPIError as exc:
                    logger.warning("could not alert chat %s: %s", chat_id, exc)
        await asyncio.sleep(agent.settings.interval_seconds)


def wire(dispatcher: Dispatcher, agent: Any, subscribers: Subscribers) -> None:
    """Start the watcher with the bot and stop it (and the agent) on shutdown."""
    tasks: list[asyncio.Task[None]] = []

    async def on_startup(bot: Bot) -> None:
        tasks.append(asyncio.create_task(watch(bot, agent, subscribers)))

    async def on_shutdown() -> None:
        for task in tasks:
            task.cancel()
            with contextlib.suppress(asyncio.CancelledError):
                await task
        await agent.close()

    dispatcher.startup.register(on_startup)
    dispatcher.shutdown.register(on_shutdown)


async def run_polling(config: BotConfig, agent: Any, subscribers: Subscribers) -> None:
    """Long polling: no public URL needed, ideal on a laptop."""
    bot = Bot(token=config.token)
    dispatcher = build_dispatcher(agent, subscribers, config.allowed)
    wire(dispatcher, agent, subscribers)
    try:
        await bot.delete_webhook(drop_pending_updates=False)
        await dispatcher.start_polling(bot)
    except TelegramAPIError as exc:
        logger.error("Telegram refused the bot: %s", exc)
    finally:
        await bot.session.close()


def run_webhook(config: BotConfig, agent: Any, subscribers: Subscribers) -> None:
    """Webhook mode: an aiohttp server Telegram calls; GET /health for the host."""
    bot = Bot(token=config.token)
    dispatcher = build_dispatcher(agent, subscribers, config.allowed)
    wire(dispatcher, agent, subscribers)

    async def set_hook(bot: Bot) -> None:
        url = config.webhook_base + WEBHOOK_PATH
        try:
            await bot.set_webhook(url, secret_token=config.webhook_secret or None)
            logger.info("webhook set: %s", url)
        except TelegramAPIError as exc:
            logger.error("could not set the webhook: %s", exc)

    async def health(_: web.Request) -> web.Response:
        return web.json_response({"status": "ok", "agent": "${slug}"})

    dispatcher.startup.register(set_hook)
    app = web.Application()
    app.router.add_get("/health", health)
    SimpleRequestHandler(dispatcher=dispatcher, bot=bot,
                         secret_token=config.webhook_secret or None).register(app,
                                                                             path=WEBHOOK_PATH)
    setup_application(app, dispatcher, bot=bot)
    web.run_app(app, host="0.0.0.0", port=config.port)


def main(argv: list[str] | None = None) -> int:
    """Parse flags, read the config and run the bot in polling or webhook mode."""
    parser = argparse.ArgumentParser(description="${name} Telegram bot")
    parser.add_argument("--webhook", action="store_true", help="serve a webhook (for a host)")
    parser.add_argument("--dry-run", action="store_true",
                        help="build the dispatcher, report it and exit (no token needed)")
    parser.add_argument("-v", "--verbose", action="store_true", help="debug logging")
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.DEBUG if args.verbose else logging.INFO,
                        format="%(asctime)s %(levelname)s %(name)s: %(message)s")
    load_dotenv()
    config = BotConfig()
    settings = Settings.from_env()
    agent = build_agent(settings)
    subscribers = Subscribers(settings.data_dir, config.chat_id)

    if args.dry_run:
        dispatcher = build_dispatcher(agent, subscribers, config.allowed)
        handlers = sum(len(r.message.handlers) for r in dispatcher.chain_tail)
        logger.info("dry run: %d handlers (%s), access list %s, token %s, mode %s",
                    handlers, ", ".join(f"/{n}" for n, _ in BOT_COMMANDS),
                    sorted(config.allowed) or "open", "set" if config.token else "missing",
                    "webhook" if args.webhook or config.webhook_base else "polling")
        asyncio.run(agent.close())
        return 0
    if not config.token:
        logger.error("set BOT_TOKEN (from @BotFather) in .env or the environment")
        return 2
    try:
        if args.webhook:
            if not config.webhook_base:
                logger.error("webhook mode needs WEBHOOK_BASE_URL (or RENDER_EXTERNAL_URL)")
                return 2
            run_webhook(config, agent, subscribers)
        else:
            asyncio.run(run_polling(config, agent, subscribers))
    except KeyboardInterrupt:
        logger.info("stopped by user")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
