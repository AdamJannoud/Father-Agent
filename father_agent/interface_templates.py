def _values(spec: SubAgentSpec, base: dict[str, str]) -> dict[str, str]:
    """Template values: the agent layout's, plus the interface's own."""
    web = spec.delivery.interface == "web"
    return {**base, "port": "8000",
            "kind": "a FastAPI dashboard" if web else "a FastAPI JSON service",
            "index_doc": " and GET / (the dashboard page)" if web else "",
            "index_route": _INDEX_ROUTE if web else "",
            "page": _PAGE if web else "",
            "html_import": "import html\n" if web else "",
            "response_import": "from fastapi.responses import HTMLResponse\n" if web else "",
            "index_test": _INDEX_TEST if web else ""}


def render_interface(spec: SubAgentSpec, base: dict[str, str]) -> str:
    """Render ``app.py`` or ``bot.py`` for ``spec`` (``base``: the agent layout's values)."""
    framework = spec.delivery.framework
    values = _values(spec, base)
    if framework == "streamlit":
        return _STREAMLIT.substitute(values)
    if framework == "fastapi":
        return _FASTAPI.substitute(values)
    if framework == "aiogram":
        return _BOT.substitute(values)
    raise ValueError(f"no interface template for {spec.delivery.label}")


def render_interface_tests(spec: SubAgentSpec, base: dict[str, str]) -> str:
    """Tests for the interface file, appended to test_agent.py (empty for cli)."""
    template = {"streamlit": _TESTS_STREAMLIT, "fastapi": _TESTS_FASTAPI,
                "aiogram": _TESTS_TELEGRAM}.get(spec.delivery.framework)
    return template.substitute(_values(spec, base)) if template else ""
