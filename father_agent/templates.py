_CLIENT_RPC = Template('''

class ${client}:
    """Reads a wallet balance over ${chain} JSON-RPC (a free public node by default)."""

    def __init__(self, settings: Settings) -> None:
        """Create the HTTP client for the configured RPC endpoint."""
        self.settings = settings
        self.rpc_url = os.environ.get("${rpc_env}", "${rpc_default}")
        self._http = httpx.AsyncClient(timeout=settings.timeout_seconds)

    async def fetch(self) -> dict[str, Any]:
        """Return the current balance of ``settings.target`` as a record."""
        if not self.settings.target:
            raise SourceError("set ${target_env} to the wallet address you want to watch")
        payload = {"jsonrpc": "2.0", "id": 1, "method": "${rpc_method}",
                   "params": ${rpc_params}}
        try:
            response = await self._http.post(self.rpc_url, json=payload)
            response.raise_for_status()
            body = response.json()
        except (httpx.HTTPError, ValueError) as exc:
            raise SourceError(f"RPC request to {self.rpc_url} failed: {exc}") from exc
        if body.get("error"):
            raise SourceError(f"RPC error: {body['error']}")
        try:
            raw = ${rpc_extract}
        except (KeyError, TypeError, ValueError) as exc:
            raise SourceError(f"unexpected RPC payload: {body}") from exc
        balance = raw / ${rpc_divisor}
        return make_record(balance, {"address": self.settings.target, "raw": str(raw),
                                     "unit": "${rpc_unit}"})

    async def aclose(self) -> None:
        """Close the HTTP connection pool."""
        await self._http.aclose()
''')

_CLIENT_HTML = Template('''

class ${client}:
    """Downloads a page and collects the text of every element matching a CSS selector."""

    def __init__(self, settings: Settings) -> None:
        """Create the HTTP client and read the selector from CSS_SELECTOR."""
        self.settings = settings
        self.selector = os.environ.get("CSS_SELECTOR", "h2")
        self._http = httpx.AsyncClient(
            timeout=settings.timeout_seconds,
            follow_redirects=True,
            headers={"User-Agent": "${slug}/1.0 (+https://github.com/father-agent)"},
        )

    async def fetch(self) -> dict[str, Any]:
        """Return the matching items on ``settings.target`` as a record."""
        if not self.settings.target:
            raise SourceError("set ${target_env} to the page you want to scrape")
        try:
            response = await self._http.get(self.settings.target)
            response.raise_for_status()
        except httpx.HTTPError as exc:
            raise SourceError(f"download of {self.settings.target} failed: {exc}") from exc
        soup = BeautifulSoup(response.text, "html.parser")
        items = [el.get_text(" ", strip=True) for el in soup.select(self.selector)]
        items = [text for text in items if text][:50]
        title = soup.title.get_text(strip=True) if soup.title else ""
        return make_record(float(len(items)), {"url": self.settings.target, "title": title,
                                               "selector": self.selector, "items": items})

    async def aclose(self) -> None:
        """Close the HTTP connection pool."""
        await self._http.aclose()
''')

_CLIENT_JSON = Template('''

class ${client}:
    """Polls a JSON HTTP API and extracts one number from the reply."""

    def __init__(self, settings: Settings) -> None:
        """Create the HTTP client; API_TOKEN, when set, is sent as a bearer token."""
        self.settings = settings
        self.field_path = os.environ.get("VALUE_FIELD", "stargazers_count")
        headers = {"Accept": "application/json", "User-Agent": "${slug}/1.0"}
        token = os.environ.get("API_TOKEN", "")
        if token:
            headers["Authorization"] = f"Bearer {token}"
        self._http = httpx.AsyncClient(timeout=settings.timeout_seconds, headers=headers)

    async def fetch(self) -> dict[str, Any]:
        """Return the tracked value from ``settings.target`` as a record."""
        try:
            response = await self._http.get(self.settings.target)
            response.raise_for_status()
            body = response.json()
        except (httpx.HTTPError, ValueError) as exc:
            raise SourceError(f"request to {self.settings.target} failed: {exc}") from exc
        value = self._extract(body)
        return make_record(value, {"url": self.settings.target, "field": self.field_path})

    def _extract(self, body: Any) -> float:
        """Walk a dotted path such as ``data.0.price`` and return it as a float."""
        current = body
        for part in self.field_path.split("."):
            if isinstance(current, list) and part.isdigit() and int(part) < len(current):
                current = current[int(part)]
            elif isinstance(current, dict) and part in current:
                current = current[part]
            else:
                raise SourceError(f"field {self.field_path!r} not found in the response")
        try:
            return float(current)
        except (TypeError, ValueError) as exc:
            raise SourceError(f"field {self.field_path!r} is not a number: {current!r}") from exc

    async def aclose(self) -> None:
        """Close the HTTP connection pool."""
        await self._http.aclose()
''')

_CLIENT_DATASET = Template('''

class ${client}:
    """Loads a CSV dataset and trains and scores a scikit-learn ${task} model on it."""

    def __init__(self, settings: Settings) -> None:
        """Read the column to predict from TARGET_COLUMN."""
        self.settings = settings
        self.target_column = os.environ.get("TARGET_COLUMN", "target")

    async def fetch(self) -> dict[str, Any]:
        """Train on ``settings.target`` in a worker thread and return the score."""
        path = Path(self.settings.target)
        if not path.is_file():
            raise SourceError(f"dataset not found: {path} (set ${target_env})")
        try:
            score, rows = await asyncio.to_thread(self._train, path)
        except (OSError, ValueError, KeyError) as exc:
            raise SourceError(f"training on {path} failed: {exc}") from exc
        return make_record(score, {"dataset": str(path), "rows": rows,
                                   "target": self.target_column, "metric": "${metric}"})

    def _train(self, path: Path) -> tuple[float, int]:
        """Blocking part: read, split, fit and score. Runs off the event loop."""
        frame = pd.read_csv(path).dropna()
        if self.target_column not in frame.columns:
            raise KeyError(f"column {self.target_column!r} is not in the dataset")
        features = frame.drop(columns=[self.target_column]).select_dtypes("number")
        if features.empty:
            raise ValueError("the dataset has no numeric feature columns")
        target = frame[self.target_column]
        x_train, x_test, y_train, y_test = train_test_split(
            features, target, test_size=0.25, random_state=42)
        model = ${estimator}(n_estimators=200, random_state=42)
        model.fit(x_train, y_train)
        return float(model.score(x_test, y_test)), int(len(frame))

    async def aclose(self) -> None:
        """Nothing to release; present so every source has the same interface."""
''')

_CLIENT_FILES = Template('''

class ${client}:
    """Scans a folder and reports how many files it holds and their total size."""

    def __init__(self, settings: Settings) -> None:
        """Read the glob of files to include from FILE_PATTERN."""
        self.settings = settings
        self.pattern = os.environ.get("FILE_PATTERN", "*")

    async def fetch(self) -> dict[str, Any]:
        """Scan ``settings.target`` in a worker thread and return a summary record."""
        root = Path(self.settings.target).expanduser()
        if not root.is_dir():
            raise SourceError(f"folder not found: {root} (set ${target_env})")
        try:
            files = await asyncio.to_thread(self._scan, root)
        except OSError as exc:
            raise SourceError(f"scanning {root} failed: {exc}") from exc
        total = sum(size for _, size, _ in files)
        newest = sorted(files, key=lambda item: item[2], reverse=True)[:10]
        return make_record(float(total), {"folder": str(root), "files": len(files),
                                          "newest": [name for name, _, _ in newest]})

    def _scan(self, root: Path) -> list[tuple[str, int, float]]:
        """Blocking part: walk the tree and stat each matching file."""
        results: list[tuple[str, int, float]] = []
        for path in root.rglob(self.pattern):
            if path.is_file():
                stat = path.stat()
                results.append((str(path.relative_to(root)), stat.st_size, stat.st_mtime))
        return results

    async def aclose(self) -> None:
        """Nothing to release; present so every source has the same interface."""
''')

