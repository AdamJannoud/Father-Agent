_HEADER = Template('''\
"""${name}: ${summary_line}

Generated by the Father Agent from the command:
    ${command}

Run it once:
    ${run_example}
Run it on a schedule (every ${interval}s by default):
    ${run_forever}
"""

from __future__ import annotations

import argparse
import asyncio
import hashlib
import json
import logging
import os
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

${third_party}

logger = logging.getLogger("${slug}")


class SourceError(Exception):
    """Raised when the data source cannot be read."""


class StoreError(Exception):
    """Raised when history cannot be read or written."""


def make_record(value: float, details: dict[str, Any]) -> dict[str, Any]:
    """Build one history record; the fingerprint ignores the timestamp."""
    fingerprint = hashlib.sha256(
        json.dumps({"value": value, "details": details}, sort_keys=True, default=str).encode()
    ).hexdigest()[:16]
    return {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "value": float(value),
        "fingerprint": fingerprint,
        "details": details,
    }


@dataclass
class Settings:
    """Runtime settings, read from environment variables with safe defaults."""

    target: str = "${default_target}"
    interval_seconds: int = ${interval}
    data_dir: Path = field(default_factory=lambda: Path("${slug}_data"))
    timeout_seconds: float = 20.0

    @classmethod
    def from_env(cls) -> Settings:
        """Build settings from ${target_env}, ${upper}_INTERVAL and ${upper}_DATA_DIR."""
        return cls(
            target=os.environ.get("${target_env}", "${default_target}"),
            interval_seconds=int(os.environ.get("${upper}_INTERVAL", "${interval}")),
            data_dir=Path(os.environ.get("${upper}_DATA_DIR", "${slug}_data")),
        )
''')

_STORE = Template('''

class ${store}:
    """Appends records to a JSON Lines file and reads the history back."""

    def __init__(self, data_dir: Path) -> None:
        """Keep history in ``<data_dir>/history.jsonl``."""
        self.path = data_dir / "history.jsonl"

    def append(self, record: dict[str, Any]) -> None:
        """Append one record, creating the folder on first use."""
        try:
            self.path.parent.mkdir(parents=True, exist_ok=True)
            with self.path.open("a", encoding="utf-8") as handle:
                handle.write(json.dumps(record, default=str) + "\\n")
        except OSError as exc:
            raise StoreError(f"cannot write {self.path}: {exc}") from exc

    def load(self) -> list[dict[str, Any]]:
        """Return every stored record, skipping corrupt lines."""
        if not self.path.exists():
            return []
        records: list[dict[str, Any]] = []
        try:
            with self.path.open(encoding="utf-8") as handle:
                for number, raw in enumerate(handle, start=1):
                    text = raw.strip()
                    if not text:
                        continue
                    try:
                        records.append(json.loads(text))
                    except json.JSONDecodeError:
                        logger.warning("skipping corrupt line %d in %s", number, self.path)
        except OSError as exc:
            raise StoreError(f"cannot read {self.path}: {exc}") from exc
        return records

    def last(self) -> dict[str, Any] | None:
        """Return the most recent record, or None when history is empty."""
        history = self.load()
        return history[-1] if history else None
''')

_PLOTTER = Template('''

class ${plotter}:
    """Draws the recorded values over time to a PNG chart."""

    def __init__(self, output_path: Path, title: str) -> None:
        """Remember where to save the chart and what to call it."""
        self.output_path = output_path
        self.title = title

    def plot(self, records: list[dict[str, Any]]) -> Path | None:
        """Render ``records`` to ``output_path``; returns None with fewer than 2 points."""
        if len(records) < 2:
            return None
        frame = pd.DataFrame(records)
        frame["timestamp"] = pd.to_datetime(frame["timestamp"])
        figure, axis = plt.subplots(figsize=(9, 4))
        try:
            axis.plot(frame["timestamp"], frame["value"], marker="o", linewidth=1.5)
            axis.set_title(self.title)
            axis.set_xlabel("time (UTC)")
            axis.set_ylabel("${value_label}")
            axis.grid(alpha=0.3)
            figure.autofmt_xdate()
            self.output_path.parent.mkdir(parents=True, exist_ok=True)
            figure.savefig(self.output_path, dpi=120, bbox_inches="tight")
        finally:
            plt.close(figure)
        return self.output_path
''')

_MAIN = Template('''

class ${main}:
    """${summary_line}"""

    def __init__(self, settings: Settings, client: Any, store: ${store},
                 plotter: ${plotter_type} = None) -> None:
        """Wire the agent to its data source, history store and optional chart."""
        self.settings = settings
        self.client = client
        self.store = store
        self.plotter = plotter

    async def run_once(self) -> dict[str, Any] | None:
        """Fetch one reading and store it if it changed.

        Returns:
            The new record when something changed, otherwise None.
        """
        try:
            record = await self.client.fetch()
        except SourceError as exc:
            logger.error("fetch failed: %s", exc)
            return None
        try:
            previous = self.store.last()
            if previous and previous.get("fingerprint") == record["fingerprint"]:
                logger.info("no change (${value_label}=%s)", record["value"])
                return None
            self.store.append(record)
        except StoreError as exc:
            logger.error("history unavailable: %s", exc)
            return None
        before = previous.get("value") if previous else None
        logger.info("change recorded: ${value_label}=%s (was %s)", record["value"], before)
        if self.plotter is not None:
            try:
                chart = await asyncio.to_thread(self.plotter.plot, self.store.load())
                if chart:
                    logger.info("chart updated: %s", chart)
            except (OSError, ValueError, StoreError) as exc:
                logger.warning("could not draw the chart: %s", exc)
        return record

    async def run_forever(self) -> None:
        """Run ``run_once`` every ``interval_seconds`` until cancelled."""
        logger.info("starting: every %ss", self.settings.interval_seconds)
        try:
            while True:
                await self.run_once()
                await asyncio.sleep(self.settings.interval_seconds)
        finally:
            await self.close()

    async def close(self) -> None:
        """Release the data source's resources."""
        try:
            await self.client.aclose()
        except Exception as exc:  # noqa: BLE001 - closing must never mask the real error
            logger.debug("error while closing the client: %s", exc)


def build_agent(settings: Settings) -> ${main}:
    """Create the agent with its real data source${plot_note}."""
    return ${main}(
        settings,
        ${client}(settings),
        ${store}(settings.data_dir),
        ${plotter_ctor},
    )


def main(argv: list[str] | None = None) -> int:
    """Command-line entry point. Returns a process exit code."""
    parser = argparse.ArgumentParser(description="${name}: ${summary_short}")
    parser.add_argument("--once", action="store_true", help="run a single cycle and exit")
    parser.add_argument("--interval", type=int, help="seconds between cycles")
    parser.add_argument("--target", help="override ${target_env}")
    parser.add_argument("-v", "--verbose", action="store_true", help="debug logging")
    args = parser.parse_args(argv)

    logging.basicConfig(level=logging.DEBUG if args.verbose else logging.INFO,
                        format="%(asctime)s %(levelname)s %(name)s: %(message)s")
    settings = Settings.from_env()
    if args.interval:
        settings.interval_seconds = args.interval
    if args.target:
        settings.target = args.target

    agent = build_agent(settings)

    async def _run() -> None:
        if args.once:
            try:
                await agent.run_once()
            finally:
                await agent.close()
        else:
            await agent.run_forever()

    try:
        asyncio.run(_run())
    except KeyboardInterrupt:
        logger.info("stopped by user")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
''')

